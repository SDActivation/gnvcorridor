const fs = require('fs');
const vm = require('vm');
const assert = require('assert/strict');
const html = fs.readFileSync('public/index.html', 'utf8');
const script = id => html.match(new RegExp(`<script id="${id}">([\\s\\S]*?)</script>`))[1];
const context = { document: { addEventListener() {} }, matchMedia: () => ({ matches: true }), console };
context.window = context;
vm.createContext(context);
for (const code of [script('illustrative-data'), fs.readFileSync('public/simulation.js', 'utf8'), script('pure-calculations'), script('inline-cartography'), script('navigator-app')]) vm.runInContext(code, context);
const run = code => vm.runInContext(code, context);
const close = (actual, expected) => assert(Math.abs(actual - expected) < 1e-6, `${actual} != ${expected}`);
const snapshot = run(`(() => {const scenario=clone(DEFAULT_SCENARIO);return {scenario,errors:validateInputs(demandData,geoData,costBenchmarks),rows:demandData.length,geo:geoData.length,sources:[...new Set(demandData.map(r=>r.source))],destinations:[...new Set(demandData.map(r=>r.destination))],geoCountries:[...new Set(geoData.map(r=>r.country))],base:evaluateScenario(scenario,costBenchmarks),zero:evaluateScenario({...scenario,budget:0},costBenchmarks),double:evaluateScenario({...scenario,budget:scenario.budget*2},costBenchmarks),high:evaluateScenario({...scenario,demandProfile:'high'},costBenchmarks),low:evaluateScenario({...scenario,demandProfile:'low'},costBenchmarks),fr:evaluateScenario({...scenario,demandDestination:'FR'},costBenchmarks),suggested:suggestAllocation(scenario,geoData),exported:createScenarioExport(scenario,costBenchmarks,null,{source:'ALL',destination:'ALL',cluster:'ALL'})};})()`);
assert.equal(snapshot.errors.length, 0);
assert.equal(snapshot.rows, 945); // 9 couples × (52 + 53) weeks.
assert.equal(snapshot.geo, 36);
assert.equal(snapshot.sources.join(','), 'MA,TN,DZ');
assert.equal(snapshot.destinations.join(','), 'FR,IT,ES');
assert.equal(snapshot.geoCountries.join(','), 'MA,TN,DZ');
assert.equal(snapshot.scenario.startWeek, 1);
assert.equal(snapshot.scenario.endWeek, 53);
assert.equal(snapshot.base.simulation.direction, 'Nord Africa → Europa');
assert.equal(snapshot.base.timingFactor, 1);
assert(snapshot.base.byWeek.every(w => w.timingFactor === 1));
close(snapshot.base.byWeek.reduce((a,w) => a+w.budget,0), snapshot.scenario.budget);
close(snapshot.base.byMarket.reduce((a,w) => a+w.incrementalSearches,0), snapshot.base.incrementalSearches);
close(snapshot.base.byChannel.reduce((a,w) => a+w.incrementalSearches,0), snapshot.base.incrementalSearches);
close(snapshot.base.simulation.weekly.reduce((a,w) => a+w.incrementalSearches,0), snapshot.base.incrementalSearches);
assert.equal(snapshot.zero.incrementalSearches, 0);
assert(snapshot.double.incrementalSearches > snapshot.base.incrementalSearches);
assert(snapshot.double.incrementalSearches < 2*snapshot.base.incrementalSearches);
assert(snapshot.high.incrementalSearches > snapshot.low.incrementalSearches);
assert(snapshot.fr.simulation.organicDemand < snapshot.base.simulation.organicDemand);
assert.equal(Object.values(snapshot.suggested.marketShares).reduce((a,b)=>a+b,0),100);
assert.equal(snapshot.suggested.budget,snapshot.scenario.budget);
assert.equal(snapshot.suggested.startWeek,1);
assert.equal(snapshot.suggested.endWeek,53);
assert.equal(Object.keys(snapshot.suggested.weekWeights).length,53);
assert.equal(JSON.stringify(snapshot.suggested.channelShares),JSON.stringify(snapshot.scenario.channelShares));
assert.equal(snapshot.exported.direction,'Nord Africa → Europa');
assert.equal(snapshot.exported.schemaVersion,'3.0');
assert.equal(snapshot.exported.assumptions.timingFactorAllWeeks,1);
assert.equal(snapshot.exported.assumptions.decisionMonths,undefined);
assert(run(`scenarioCSV(createScenarioExport(DEFAULT_SCENARIO,costBenchmarks,null,{})).includes('Nord Africa → Europa')`));
run(`const frozen=evaluateScenario({...DEFAULT_SCENARIO,demandProfile:'base'},costBenchmarks).incrementalSearches; GNVSimulation.setProfile('high'); if(validateInputs(demandData,geoData,costBenchmarks).length)throw Error('high invalid');if(evaluateScenario({...DEFAULT_SCENARIO,demandProfile:'base'},costBenchmarks).incrementalSearches!==frozen)throw Error('snapshot changed'); GNVSimulation.setProfile('low');if(validateInputs(demandData,geoData,costBenchmarks).length)throw Error('low invalid'); GNVSimulation.setProfile('base');`);
for (const [id,countries] of [['source-filter',['MA','TN','DZ']],['destination-filter',['FR','IT','ES']],['simulation-destination',['FR','IT','ES']]]) {
  const select = html.match(new RegExp(`<select id="${id}">([\\s\\S]*?)</select>`))[1];
  const values = [...select.matchAll(/value="([^"]+)"/g)].map(m=>m[1]);
  assert.equal(values.join(','), ['ALL',...countries].join(','));
}
assert(!html.includes('Europa → Maghreb'));
assert(!html.includes('diasporaIndex'));
assert(!html.includes('0,45 altrove'));
console.log('OK: Nord Africa → Europa; 945 righe, 36 città, filtri, budget, saturazione, profili, calendario neutro, suggerimenti, export e snapshot.');
